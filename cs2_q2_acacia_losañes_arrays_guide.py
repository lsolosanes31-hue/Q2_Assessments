study_hours = [2.5, 4.0, 3.0, 5.5, 4.5]


def display_hours(hours):
    print("\n--- Recorded Study Hours ---")
    for i in range(len(hours)):
        print(f"Day {i + 1} (Index {i}): {hours[i]} hrs")


def search_hours(hours, target):
    found = False
    for i in range(len(hours)):
        if hours[i] == target:
            print(f"Found {target} hrs on Day {i + 1} (Index {i}).")
            found = True
    if not found:
        print(f"{target} hrs was not found in the list.")


def compute_average(hours):
    if len(hours) == 0:
        print("No study hours to compute.")
        return
    total = 0
    for h in hours:
        total += h
    average = total / len(hours)
    print("\n--- Study Hours Summary ---")
    print(f"Total Hours:   {total:.2f} hrs")
    print(f"Average Hours: {average:.2f} hrs")


def update_hours(hours, index, new_value):
    if 0 <= index < len(hours):
        old_value = hours[index]
        hours[index] = new_value
        print(f"Updated Index {index} from {old_value} to {new_value}.")
    else:
        print(f"Invalid index! Please enter a number from 0 to {len(hours) - 1}.")


def display_updated_hours(hours):
    print("\n--- Updated Study Hours ---")
    for i in range(len(hours)):
        print(f"Day {i + 1} (Index {i}): {hours[i]} hrs")


def main():
    while True:
        print("\n=== Daily Study Hours Analyzer ===")
        print("\nSelect the number of the operation you want to perform:\n")
        print("1. Display Study Hours")
        print("2. Search Study Hours")
        print("3. Compute Average Study Hours")
        print("4. Update Study Hours")
        print("5. Display Updated Study Hours")
        print("6. Exit")

        choice = input("\nEnter your choice: ").strip()

        if choice == "1":
            display_hours(study_hours)
        elif choice == "2":
            target = float(input("Enter study hours to search: "))
            search_hours(study_hours, target)
        elif choice == "3":
            compute_average(study_hours)
        elif choice == "4":
            index = int(input(f"Enter index to update (0-{len(study_hours) - 1}): "))
            new_value = float(input("Enter new study hours value: "))
            update_hours(study_hours, index, new_value)
        elif choice == "5":
            display_updated_hours(study_hours)
        elif choice == "6":
            print("Exiting program. Goodbye!")
            break
        else:
            print("Invalid choice. Please select a number from 1 to 6.")


if __name__ == "__main__":
    main()

